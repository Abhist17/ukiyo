// Copies the ABIs and the known deployments into src/, so the SDK ships them without Foundry or the web app.
// Run from sdk/ after `forge build`:  npm run gen
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const OUT = new URL("../../out/", import.meta.url);
const WANT = {
  hookAbi: "UkiyoHook.sol/UkiyoHook.json",
  lensAbi: "UkiyoLens.sol/UkiyoLens.json",
  vaultAbi: "UkiyoVault.sol/UkiyoVault.json",
  factoryAbi: "UkiyoFactory.sol/UkiyoFactory.json",
};

let abi = "// Generated by scripts/gen.mjs from Foundry's out/. Do not edit by hand.\n";
for (const [name, file] of Object.entries(WANT)) {
  // events, views and the writes an integrator calls; constructors and errors are kept too, so reverts decode
  const { abi: a } = JSON.parse(readFileSync(new URL(file, OUT), "utf8"));
  abi += `\nexport const ${name} = ${JSON.stringify(a)} as const;\n`;
}
writeFileSync(new URL("../src/abi.ts", import.meta.url), abi);

const dir = new URL("../../web/src/deployments/", import.meta.url);
const deps = {};
for (const f of readdirSync(dir).filter((f) => /^\d+\.json$/.test(f) && f !== "31337.json")) {
  const d = JSON.parse(readFileSync(new URL(f, dir), "utf8"));
  deps[d.chainId] = d;
}
writeFileSync(
  new URL("../src/deployments.generated.ts", import.meta.url),
  "// Generated by scripts/gen.mjs from web/src/deployments/. Do not edit by hand.\n" +
    `export const DEPLOYMENTS_JSON = ${JSON.stringify(deps, null, 2)} as const;\n`,
);
console.log("wrote src/abi.ts and src/deployments.generated.ts:", Object.keys(deps).join(", "));
