// Copies the ABIs the site and the bot need from Foundry's build output into src/lib/abi.ts.
// Run from web/ after `forge build`:  node scripts/abi.mjs
import { readFileSync, writeFileSync } from "node:fs";

const OUT = new URL("../../out/", import.meta.url);
const WANT = {
  hookAbi: "UkiyoHook.sol/UkiyoHook.json",
  vaultAbi: "UkiyoVault.sol/UkiyoVault.json",
  tokenAbi: "MockERC20.sol/MockERC20.json",
  routerAbi: "PoolSwapTest.sol/PoolSwapTest.json",
};

let src = "// Generated by scripts/abi.mjs from Foundry's out/. Do not edit by hand.\n";
for (const [name, file] of Object.entries(WANT)) {
  const { abi } = JSON.parse(readFileSync(new URL(file, OUT), "utf8"));
  src += `\nexport const ${name} = ${JSON.stringify(abi)} as const;\n`;
}
writeFileSync(new URL("../src/lib/abi.ts", import.meta.url), src);
console.log("wrote src/lib/abi.ts");
