// Copies the ABIs the site and the bot need from Foundry's build output into src/lib/abi.ts.
// Run from web/ after `forge build`:  node scripts/abi.mjs
import { readFileSync, writeFileSync, readdirSync } from "node:fs";

const OUT = new URL("../../out/", import.meta.url);
const WANT = {
  hookAbi: "UkiyoHook.sol/UkiyoHook.json",
  vaultAbi: "UkiyoVault.sol/UkiyoVault.json",
  factoryAbi: "UkiyoFactory.sol/UkiyoFactory.json",
  tokenAbi: "MockERC20.sol/MockERC20.json",
  routerAbi: "PoolSwapTest.sol/PoolSwapTest.json",
};

let src = "// Generated by scripts/abi.mjs from Foundry's out/. Do not edit by hand.\n";
for (const [name, file] of Object.entries(WANT)) {
  const { abi } = JSON.parse(readFileSync(new URL(file, OUT), "utf8"));
  src += `\nexport const ${name} = ${JSON.stringify(abi)} as const;\n`;
}
writeFileSync(new URL("../src/lib/abi.ts", import.meta.url), src);
console.log("wrote src/lib/abi.ts");

// The vault's creation code, which UkiyoFactory.launch takes as calldata (it is too large for the factory to embed).
// Its own module, so only the launch form loads its ~50 KB.
const vault = JSON.parse(readFileSync(new URL(WANT.vaultAbi, OUT), "utf8"));
writeFileSync(
  new URL("../src/lib/vaultCode.ts", import.meta.url),
  "// Generated by scripts/abi.mjs from Foundry's out/. Do not edit by hand.\n" +
    `export const VAULT_CODE = "${vault.bytecode.object}" as const;\n`,
);
console.log("wrote src/lib/vaultCode.ts");

// Index of deployments, so the site picks up a new chain's file without hand edits.
const dir = new URL("../src/deployments/", import.meta.url);
const ids = readdirSync(dir).filter((f) => /^\d+\.json$/.test(f)).map((f) => f.replace(".json", ""));
let idx = "// Generated by scripts/abi.mjs from the files deploy writes here. Do not edit by hand.\n";
for (const id of ids) idx += `import d${id} from "./${id}.json";\n`;
idx += `\nexport const DEPLOYMENTS = { ${ids.map((id) => `${id}: d${id}`).join(", ")} } as const;\n`;
writeFileSync(new URL("index.ts", dir), idx);
console.log("wrote src/deployments/index.ts:", ids.join(", "));
